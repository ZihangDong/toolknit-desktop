export const TOOLKNIT_ART_WIDTH = Math.max(...TOOLKNIT_ART_LINES.map(line => line.length));

export function normalizeBannerMode(value) {
  const mode = value ?? 'auto';
  if (mode !== 'auto' && mode !== 'always' && mode !== 'never') {
    throw new Error('--banner must be auto, always, or never.');
  }
  return mode;
}

function colorizeEyes(line, color) {
  if (!color) return line;
  return line.replaceAll('iiiiiiiii', '\x1b[91miiiiiiiii\x1b[0m');
}

export function renderToolKnitBanner({
  mode = 'auto',
  isTTY = process.stdout.isTTY === true,
  columns = process.stdout.columns,
  color = isTTY && !process.env.NO_COLOR
} = {}) {
  const normalizedMode = normalizeBannerMode(mode);
  if (normalizedMode === 'never' || (normalizedMode === 'auto' && !isTTY)) return '';
  if (normalizedMode === 'always' || (Number.isInteger(columns) && columns >= TOOLKNIT_ART_WIDTH + 4)) {
    return TOOLKNIT_ART_LINES.map(line => colorizeEyes(line, color)).join('\n');
  }
  return 'ToolKnit CLI / local file tools';
}
