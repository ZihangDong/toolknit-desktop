import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { createServer } from 'vite';

const require = createRequire(process.env.TOOLKNIT_TEST_MODULES ? path.join(process.env.TOOLKNIT_TEST_MODULES, 'package.json') : import.meta.url);
const { chromium } = require('playwright');
const output = path.resolve('tmp/xml-browser');
await mkdir(output, { recursive: true });
const server = await createServer({ server: { host: '127.0.0.1', port: 0, open: false }, logLevel: 'error' });
await server.listen();
const browser = await chromium.launch({ headless: true, ...(process.env.TOOLKNIT_TEST_BROWSER ? { executablePath: process.env.TOOLKNIT_TEST_BROWSER } : { channel: 'msedge' }) });
const errors = [], requests = [], checks = [];
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, reducedMotion: 'reduce', permissions: ['clipboard-read', 'clipboard-write'] });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (!request.url().startsWith(server.resolvedUrls.local[0])) requests.push(request.url()); });
  await page.addInitScript(() => {
    localStorage.setItem('toolknit-lang', 'zh');
    localStorage.setItem('toolknit.theme.v3', 'light');
    localStorage.setItem('toolknit.recording-mode.prompt-dismissed.v1', 'true');
  });
  await page.goto(server.resolvedUrls.local[0]);
  await page.waitForFunction(() => !document.getElementById('appStartupMask') && !document.querySelector('.app')?.inert);
  const cases = await page.evaluate(async () => {
    const { formatXmlText } = await import('/src/features/developer-toolbox/xml.js');
    const result = [];
    const equal = (name, input, expected, indent = '2') => {
      const actual = formatXmlText(input, indent);
      if (actual !== expected) throw new Error(`${name}: ${JSON.stringify(actual)} != ${JSON.stringify(expected)}`);
      if (formatXmlText(actual, indent) !== actual) throw new Error(`${name}: formatting is not idempotent`);
      result.push(name);
    };
    const rejects = (name, input, code, indent = '2') => {
      let failure;
      try { formatXmlText(input, indent); } catch (error) { failure = error; }
      if (failure?.message !== code) throw new Error(`${name}: expected ${code}, got ${failure?.message}`);
      result.push(name);
    };
    equal('nested elements', '<root><item a="1 > 0">中文 &amp; English</item><empty/></root>', '<root>\n  <item a="1 > 0">中文 &amp; English</item>\n  <empty/>\n</root>');
    equal('four spaces', '<r><a><b/></a></r>', '<r>\n    <a>\n        <b/>\n    </a>\n</r>', '4');
    equal('tabs', '<r><a/></r>', '<r>\n\t<a/>\n</r>', 'tab');
    equal('minify layout', '<r>\n  <a/>\n  <b>  </b>\n</r>', '<r><a/><b>  </b></r>', '0');
    equal('mixed content', '<p>Hello <b><i>world</i></b> !</p>', '<p>Hello <b><i>world</i></b> !</p>');
    equal('mixed content spaces', '<p><b/> <i/></p>', '<p><b/> <i/></p>');
    equal('preserved inline whitespace', '<p xml:space="preserve"><b/> <i/></p>', '<p xml:space="preserve"><b/> <i/></p>', '0');
    equal('whitespace leaf', '<r>   </r>', '<r>   </r>', '0');
    equal('preserve subtree', '<r><a xml:space="preserve"> \n<b><c/></b> </a><x/></r>', '<r>\n  <a xml:space="preserve"> \n<b><c/></b> </a>\n  <x/>\n</r>');
    equal('encoded xml:space', '<r xml:space="pre&#x73;erve"><a/> <b/></r>', '<r xml:space="pre&#x73;erve"><a/> <b/></r>');
    equal('attribute does not impersonate xml:space', '<r note=" xml:space=\'preserve\'"><a/></r>', '<r note=" xml:space=\'preserve\'">\n  <a/>\n</r>');
    equal('CDATA', '<r><a><![CDATA[<b> & text]]></a></r>', '<r>\n  <a><![CDATA[<b> & text]]></a>\n</r>');
    equal('namespaces and comment', '<x:r xmlns:x="urn:toolknit"><!--keep--><x:a v=\'&#65;\'/></x:r>', '<x:r xmlns:x="urn:toolknit">\n  <!--keep-->\n  <x:a v=\'&#65;\'/>\n</x:r>');
    equal('declaration and processing instruction', '<?xml version="1.0"?><r><?keep value?><a/></r><!--end-->', '<?xml version="1.0"?>\n<r>\n  <?keep value?>\n  <a/>\n</r>\n<!--end-->');
    equal('DOCTYPE quotes and internal entity', '<!DOCTYPE r [<!ENTITY text "a > [b]">]><r>&text;</r>', '<!DOCTYPE r [<!ENTITY text "a > [b]">]>\n<r>&text;</r>');
    equal('doctype comment brackets', '<!DOCTYPE r [<!-- ] > [ --><!ENTITY a "ok">]><r>&a;</r>', '<!DOCTYPE r [<!-- ] > [ --><!ENTITY a "ok">]>\n<r>&a;</r>');
    equal('parsererror tag is ordinary XML', '<parsererror/>', '<parsererror/>');
    equal('external DTD stays inert', '<!DOCTYPE r SYSTEM "https://xml-resource.test/example.dtd"><r/>', '<!DOCTYPE r SYSTEM "https://xml-resource.test/example.dtd">\n<r/>');
    equal('empty input', ' \n ', '');
    for (const input of ['<r><a></r>', '<r/><a/>', '<r x="1" x="2"/>', '<x:r/>', '<r>&unknown;</r>', '<r><!--unfinished</r>', '<r><![CDATA[unfinished</r>', '<r x="unfinished/>']) rejects(`invalid ${input}`, input, 'xml:invalid');
    rejects('input budget', 'x'.repeat(2 * 1024 * 1024 + 1), 'developer-tool:input-too-large');
    rejects('depth budget', '<a>'.repeat(257) + '</a>'.repeat(257), 'xml:too-deep');
    rejects('token budget', '<r>' + '<a/>'.repeat(100001) + '</r>', 'xml:too-complex');
    const large = '<a>'.repeat(250) + '<b/>'.repeat(12000) + '</a>'.repeat(250);
    rejects('expanded output budget', large, 'xml:output-too-large', '4');
    equal('minify avoids expansion', large, large, '0');
    return result;
  });
  checks.push(...cases);
  const root = page.locator('#developerToolboxOverlay');
  await page.locator('#homeToolSearch').fill('XML');
  await page.locator('[data-home-tool="xml-tools"]').click();
  await root.locator('[data-dev-input]').waitFor({ state: 'visible' });
  const input = root.locator('[data-dev-input]'), result = root.locator('[data-dev-output]');
  await input.fill('<root><item>ToolKnit</item><empty/></root>');
  await page.waitForFunction(() => document.querySelector('[data-dev-output]')?.value.includes('\n  <item>'));
  await root.locator('[data-json-indent-trigger]').click();
  await root.locator('[data-json-indent-option="0"]').click();
  assert.equal(await result.inputValue(), '<root><item>ToolKnit</item><empty/></root>');
  await root.locator('[data-dev-copy]').click();
  assert.equal(await page.evaluate(() => navigator.clipboard.readText()), await result.inputValue());
  await input.fill('<root><a></root>');
  await page.waitForFunction(() => document.querySelector('[data-dev-status]')?.classList.contains('is-error'));
  assert.equal(await result.inputValue(), '', 'invalid XML clears stale output');
  assert.match(await root.locator('[data-dev-status]').textContent(), /XML 格式错误/);
  await page.screenshot({ path: path.join(output, 'xml-error.png') });
  await input.fill('<root><item>恢复</item></root>');
  await page.waitForFunction(() => document.querySelector('[data-dev-status]')?.textContent === 'XML 有效');
  await page.evaluate(async () => (await import('/src/i18n.js')).setLangWithoutFade('en'));
  assert.equal(await root.locator('[data-dev-title]').innerText(), 'XML Formatter');
  assert.equal(await input.inputValue(), '<root><item>恢复</item></root>', 'language switch preserves input');
  assert.equal(await root.locator('[data-json-indent]').inputValue(), '0', 'language switch preserves indentation');
  await root.locator('[data-json-indent-trigger]').click();
  await page.keyboard.press('Escape');
  assert.equal(await root.locator('[data-json-indent-trigger]').getAttribute('aria-expanded'), 'false');
  await root.locator('[data-json-indent-trigger]').click();
  await root.locator('[data-json-indent-option="2"]').click();
  for (const [theme, width] of [['light', 1440], ['dark', 1440], ['light', 1024], ['light', 390]]) {
    await page.setViewportSize({ width, height: 900 });
    await page.evaluate(theme => { document.documentElement.dataset.theme = theme; }, theme);
    const overflow = await root.evaluate(node => node.scrollWidth > node.clientWidth + 2);
    assert.equal(overflow, false, `XML shell overflow at ${theme}/${width}`);
    await page.screenshot({ path: path.join(output, `xml-${theme}-${width}.png`) });
  }
  await page.setViewportSize({ width: 1440, height: 900 });
  await input.fill('<root/>');
  await root.locator('[data-dev-clear]').click();
  assert.equal(await input.inputValue(), '');
  assert.equal(await result.inputValue(), '');
  assert.equal(await root.locator('[data-dev-status]').innerText(), 'Cleared');
  await input.fill('<root/>');
  await root.locator('[data-dev-tool="json-tools"]').click();
  await root.locator('[data-dev-input]').fill('{"a":1}');
  await page.waitForFunction(() => document.querySelector('[data-dev-output]')?.value.includes('"a": 1'));
  await root.locator('[data-dev-tool="xml-tools"]').click();
  assert.equal(await input.inputValue(), '', 'switching modes clears previous session input');
  await input.fill('<secret>session only</secret>');
  await root.locator('[data-dev-close]').click();
  assert.equal(await input.inputValue(), '', 'closing clears sensitive input');
  assert.equal(await result.inputValue(), '');
  assert.deepEqual(requests.filter(url => url.includes('xml-resource.test')), [], 'XML external resources never load');
  assert.deepEqual(errors, []);
  checks.push('home search and lazy launch', 'indent menu and minify', 'clipboard copy', 'invalid input recovery', 'language switch retains data', 'Escape closes indent menu', 'light/dark and responsive layout', 'clear cancels pending work', 'JSON regression and mode isolation', 'close clears session', 'no external XML requests');
  await writeFile(path.join(output, 'report.json'), JSON.stringify({ passed: true, checks, errors }, null, 2));
  console.log(`XML browser tests passed: ${checks.length} formatting, error, limit and UI checks.`);
} finally {
  await browser.close();
  await server.close();
}
